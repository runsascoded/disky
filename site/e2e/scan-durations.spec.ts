import { expect, test } from '@playwright/test'

test.skip(process.env.SCAN_DURATIONS_PREVIEW !== '1', 'set SCAN_DURATIONS_PREVIEW=1 against the local dev server')
test.use({ actionTimeout: 5000, colorScheme: 'dark' })

test('breaks the empty range, retains both outlier pieces, and restores the full scale', async ({ page }) => {
  await page.goto('/dev/scan-durations')
  await expect(page.locator('.sr-cut-note')).toHaveText('Y-axis break: 15–95h omitted. Bar heights use the same scale on both sides.')
  const outlier = page.getByRole('link', { name: '2026-11-03T1800 ingest run', exact: true })
  await expect(outlier.locator('.sr-col-total')).toHaveCount(2)
  await expect(outlier.locator('.sr-break-mark')).toHaveCount(1)
  await expect(page.locator('.sr-strip .sr-y-tick')).toHaveText(['0h', '5h', '10h', '15h', '95h', '96h', '97h', '98h'])
  await page.screenshot({ path: '../tmp/scan-durations-desktop.png', fullPage: true })
  await page.getByRole('button', { name: 'full', exact: true }).click()
  expect(new URL(page.url()).searchParams.get('yb')).toBe('0')
  await expect(page.locator('.sr-cut-note')).toHaveCount(0)
  await expect(outlier.locator('.sr-col-total')).toHaveCount(1)
  await page.getByRole('button', { name: 'auto break', exact: true }).click()
  expect(new URL(page.url()).searchParams.get('yb')).toBe(null)
  await expect(outlier.locator('.sr-col-total')).toHaveCount(2)
})

test('reuses week/month/all zoom without changing selected rows, and restores it from the URL', async ({ page }) => {
  await page.goto('/dev/scan-durations?w=2026-10-31T0600~2026-11-05T0600')
  await expect(page.getByRole('status', { name: 'Selected runs', exact: true })).toHaveText('11 / 76 runs selected')
  await page.getByRole('radio', { name: '1w', exact: true }).click()
  await expect(page.locator('.sr-col')).toHaveCount(15)
  expect(Object.fromEntries(new URL(page.url()).searchParams)).toEqual({ w: '2026-10-31T0600~2026-11-05T0600', xr: '1w' })
  await expect(page.getByRole('status', { name: 'Selected runs', exact: true })).toHaveText('11 / 76 runs selected')
  await page.reload()
  await expect(page.locator('.sr-col')).toHaveCount(15)
  await page.getByRole('radio', { name: '1m', exact: true }).click()
  await expect(page.locator('.sr-col')).toHaveCount(61)
  await page.getByRole('radio', { name: 'all', exact: true }).click()
  await expect(page.locator('.sr-col')).toHaveCount(76)
  await page.getByRole('button', { name: 'zoom to selected runs', exact: true }).click()
  expect(new URL(page.url()).searchParams.get('xr')).toBe('2026-10-30T1800..2026-11-05T1800')
  await expect(page.locator('.sr-col')).toHaveCount(13)
  await page.goto('/dev/scan-durations?xr=2026-11-04T0600..2026-11-07T1800')
  await expect(page.locator('.sr-col')).toHaveCount(8)
  await expect(page.locator('.sr-cut-note')).toHaveCount(0)
  await expect(page.locator('.sr-strip .sr-y-tick')).toHaveText(['0h', '1h', '2h', '3h'])
})

test('overview brushing zooms, double-click resets, and the selection remains independent', async ({ page }) => {
  await page.goto('/dev/scan-durations?w=2026-10-31T0600~2026-11-05T0600')
  const overview = page.getByRole('group', { name: 'Scan runs: drag to zoom, double-click for all dates', exact: true })
  const box = await overview.boundingBox()
  expect(box === null).toBe(false)
  const x = (i: number) => box!.x + 56 + i / 75 * (box!.width - 72)
  await page.mouse.move(x(60), box!.y + 13)
  await page.mouse.down()
  await page.mouse.move(x(70), box!.y + 13, { steps: 10 })
  await page.mouse.up()
  expect(Object.fromEntries(new URL(page.url()).searchParams)).toEqual({ w: '2026-10-31T0600~2026-11-05T0600', xr: '2026-10-31T0600..2026-11-05T0600' })
  await expect(page.locator('.sr-col')).toHaveCount(11)
  await overview.dblclick()
  await expect(page.locator('.sr-col')).toHaveCount(76)
  expect(Object.fromEntries(new URL(page.url()).searchParams)).toEqual({ w: '2026-10-31T0600~2026-11-05T0600' })
})

