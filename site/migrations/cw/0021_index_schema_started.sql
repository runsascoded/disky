-- A scan's start instant on its pointer row: `index_schema.started` (ISO 8601,
-- UTC), the snapshot's `meta.started` as `dt-cloud index-sync -m <meta.json>`
-- records it. The scan picker reads every date-only scan's start from here in
-- one query (`/data/<store>/scan-times.json`), where it used to fetch each
-- scan's `meta.json`.
--
-- Additive: one nullable column, no rebuild. NULL = not known (a scan synced
-- before this, or by a sync that named no meta); the picker then shows the
-- date alone. `index-sync` never clears a known value: its pointer write is an
-- upsert that names `started` only when it has one.
ALTER TABLE index_schema ADD COLUMN started TEXT;
