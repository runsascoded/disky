#!/usr/bin/env node
// The build's identity — its commit and when it was built — so a bug report pins the deploy that served it (a
// request answered by a not-yet-updated isolate reads as a bug otherwise). Written to `functions/_lib/build.gen.ts`
// (untracked, `site/.gitignore`), which the Functions bundle imports (`_lib/build.ts`: the `x-disky-build` header on
// every response, `/api/health`'s `build`); `vite.config.ts` writes the same file and defines the client's copy, so
// one build's page and Functions agree. Run before anything bundles or typechecks the Functions without Vite: `pnpm
// build` (before `tsc`), `./dev` (before `wrangler pages dev`); `vitest.config.ts` writes it too.
//
// The commit: `VITE_BUILD_SHA` if set, else the checkout's `git rev-parse --short=10 HEAD` (+ `-dirty` when tracked
// files differ from it), else `GITHUB_SHA`'s first 10, else `unknown`. The checkout first: under a `workflow_run`
// (deploy-r2.yml) `GITHUB_SHA` is the default branch's tip, not the commit checked out and built.
import { execFileSync } from 'node:child_process'
import { writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const SITE = join(dirname(fileURLToPath(import.meta.url)), '..')
export const BUILD_GEN = join(SITE, 'functions/_lib/build.gen.ts')

const git = args => execFileSync('git', args, { cwd: SITE, stdio: ['ignore', 'pipe', 'ignore'] }).toString().trim()

/** The commit this build is of (see above). */
export function buildSha(env = process.env) {
  if (env.VITE_BUILD_SHA) return env.VITE_BUILD_SHA
  try {
    const sha = git(['rev-parse', '--short=10', 'HEAD'])
    return git(['status', '--porcelain', '--untracked-files=no']) ? `${sha}-dirty` : sha
  } catch {
    return env.GITHUB_SHA ? env.GITHUB_SHA.slice(0, 10) : 'unknown'
  }
}

/** `{ sha, time }` (time: ISO 8601 UTC, seconds), written to `BUILD_GEN`; returned. */
export function writeBuildId(now = new Date()) {
  const id = { sha: buildSha(), time: now.toISOString().replace(/\.\d{3}Z$/, 'Z') }
  writeFileSync(BUILD_GEN, `// Generated by scripts/build-id.mjs: this build's commit and time. Not tracked.\nexport const BUILD = ${JSON.stringify(id)} as const\n`)
  return id
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const id = writeBuildId()
  console.error(`build-id: ${id.sha} ${id.time}`)
}
