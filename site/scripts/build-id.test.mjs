import { test } from 'node:test'
import { deepStrictEqual, strictEqual } from 'node:assert'
import { readFileSync } from 'node:fs'
import { buildSha, BUILD_GEN, writeBuildId } from './build-id.mjs'

test('a detached release explicitly carries its full source revision, branch and environment', () => {
  const env = { VITE_BUILD_SHA: 'a'.repeat(40), VITE_SOURCE_REF: 'hf', VITE_BUILD_ENVIRONMENT: 'dev' }
  const id = writeBuildId(new Date('2026-11-10T12:34:56.789Z'), env)
  deepStrictEqual(id, { sha: 'a'.repeat(40), time: '2026-11-10T12:34:56Z', ref: 'hf', environment: 'dev' })
  strictEqual(readFileSync(BUILD_GEN, 'utf8'), `// Generated by scripts/build-id.mjs: this build's commit and time. Not tracked.\nexport const BUILD = ${JSON.stringify(id)} as const\n`)
})

test('an explicit source stamp wins over workflow_run controller identity', () => {
  strictEqual(buildSha({ VITE_BUILD_SHA: 'a'.repeat(40), GITHUB_SHA: 'b'.repeat(40) }), 'a'.repeat(40))
})
