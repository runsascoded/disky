"""`dt_cloud.scan_dag`: a scan's DAG built from its profile (specs/orchestrator-abstraction.md §1), and
`scan_dag_nf`'s rendering of it as `scan.nf` (§2; a golden file). That Nextflow runs the rendered file as this graph is
`test_scan_nf.py`'s (`-preview` reduced by `run_dag`)."""
from __future__ import annotations

import json
from pathlib import Path

import pytest

from dt_cloud.scan_dag import Call, Node, ScanDag, Task, build, resources
from dt_cloud.scan_dag_nf import body, render
from dt_cloud.scan_profile import Disk, Machine, load, parse

FIX = Path(__file__).parent / "fixtures" / "scan_profiles"
REPO = Path(__file__).resolve().parents[2]

Shape = tuple[str, str, tuple[str, ...], list]


def shape(d: ScanDag) -> list[Shape]:
    """Each node as `(name, label, deps, calls)`: `calls` the one task's calls as strings, or a fan-out's
    `[(tag, calls), …]`."""
    def calls(t: Task) -> list[str]:
        return [str(c) for c in t.calls]
    return [(n.name, n.label, n.deps, [(t.tag, calls(t)) for t in n.tasks] if n.fanout else calls(n.tasks[0])) for n in d.nodes]


def prof(**kw) -> object:
    return parse({"deployment": "fix", "executor": {"kind": "local"}, "work": "/w", "data": "/d",
                  "layout": {"layer2": "l2/{scan}/", "snapshots": "", "listing": "listing/{scan}/"}, "sources": ["gs://a"], **kw})


SERVE = ["index_rows", "static_names", "interval_store"]


def test_cw():
    """cw's shape: bucket-check folded into the first list task, index-sync into post; over-time its own task."""
    d = build(load(FIX / "cw-s3.yml"))
    assert shape(d) == [
        ("list_source", "list", (), [("s3://bucket-big", ["bucket-check", "list s3://bucket-big"]),
                                     ("s3://bucket-b", ["list s3://bucket-b"]), ("s3://bucket-c", ["list s3://bucket-c"])]),
        ("index", "big", ("list_source",), ["index"]),
        ("index_rows", "small", ("index",), ["index-rows"]),
        ("publish_r2", "medium", ("index_rows",), ["publish-r2"]),
        ("static_names", "small", ("index",), ["static-names"]),
        ("interval_store", "big", ("publish_r2",), ["interval-store"]),
        ("post", "post", tuple(SERVE), ["index-sync", "index-gc", "warm-cache", "probe", "digest"]),
        ("over_time", "post", tuple(SERVE), ["over-time"]),
    ]
    assert json.loads(d.graph().to_json()) == {
        "nodes": [{"id": n, "label": n} for n in d.names],
        "edges": [["list_source", "index"], ["index", "index_rows"], ["index", "static_names"],
                  ["index_rows", "over_time"], ["index_rows", "post"], ["index_rows", "publish_r2"],
                  ["publish_r2", "interval_store"], ["static_names", "over_time"], ["static_names", "post"],
                  ["interval_store", "over_time"], ["interval_store", "post"]],
    }
    assert d["static_names"].time == "6h"
    assert (d["list_source"].fanout, d["list_source"].retries) == ("sources", 1)


def test_cw_rendered_golden():
    assert body(build(load(FIX / "cw-s3.yml"))) == (FIX / "cw-s3.scan.nf").read_text()


def test_render_is_the_prelude_then_the_body():
    d = build(load(FIX / "cw-s3.yml"))
    prelude = (REPO / "job/nf/prelude.nf").read_text()
    assert render(d, prelude, "cw-s3") == (
        "// Generated by `dt-cloud scan head` from the cw-s3 profile's scan DAG (`scan_dag`): not edited by hand.\n"
        f"{prelude.rstrip()}\n\n{body(d)}")


def test_unfolded():
    """`fold: []`: bucket-check and index-sync each their own task."""
    d = build(prof(fold=[], skip=["digest", "static-names", "over-time"]))
    assert shape(d) == [
        ("bucket_check", "small", (), ["bucket-check"]),
        ("list_source", "list", (), [("gs://a", ["list gs://a"])]),
        ("index", "big", ("bucket_check", "list_source"), ["index"]),
        ("index_rows", "small", ("index",), ["index-rows"]),
        ("publish_r2", "medium", ("index_rows",), ["publish-r2"]),
        ("interval_store", "big", ("publish_r2",), ["interval-store"]),
        ("index_sync", "small", ("index_rows", "interval_store"), ["index-sync"]),
        ("post", "post", ("index_sync",), ["index-gc", "warm-cache", "probe"]),
    ]


def test_reproc_runs_from_index():
    """REPROC (`scan head -R`) without an adopted listing: no list or bucket-check task; `pre` steps still run."""
    d = build(prof(steps=["access-ingest", "healthcheck"], skip=["digest", "static-names"], options={"list": {"import": True}}),
              reproc=True)
    assert shape(d) == [
        ("pre", "small", (), ["access-ingest"]),
        ("index", "big", ("pre",), ["index"]),
        ("index_rows", "small", ("index",), ["index-rows"]),
        ("publish_r2", "medium", ("index_rows",), ["publish-r2"]),
        ("interval_store", "big", ("publish_r2",), ["interval-store"]),
        ("post", "post", ("index_rows", "interval_store"), ["index-sync", "index-gc", "healthcheck", "warm-cache", "probe"]),
        ("over_time", "post", ("index_rows", "interval_store"), ["over-time"]),
    ]


def test_reproc_keeps_an_adopted_listing():
    """A source adopting its listing (`sources[].listing`) keeps its list task under REPROC (on a local data dir its
    shards have no other copy); bucket-check folds into it as into any first list task."""
    p = prof(sources=[{"uri": "r2://disk-tree", "listing": "{env:DT_CAPTURE}"}, "r2://other"],
             layout={"layer2": "l2/{scan}/", "snapshots": "", "listing": "cap/{scan}/"}, skip=["digest", "static-names"])
    assert [shape(build(p, reproc=r))[0] for r in (True, False)] == [
        ("list_source", "list", (), [("r2://disk-tree", ["bucket-check", "list r2://disk-tree"])]),
        ("list_source", "list", (), [("r2://disk-tree", ["bucket-check", "list r2://disk-tree"]), ("r2://other", ["list r2://other"])]),
    ]


def test_side_steps_get_their_own_task():
    """`non-live` (stage `side`) runs as its own task from the start, never in `pre` (which `index` waits on);
    publish-r2 and serving wait on it. `machines.side` sizes it."""
    base = dict(steps=["access-ingest", "non-live"], skip=["digest", "static-names", "over-time"],
                options={"list": {"import": True}, "non-live": {"classes": ["soft-deleted"]}})
    d = build(prof(**base))
    assert shape(d) == [
        ("pre", "small", (), ["access-ingest"]),
        ("list_source", "list", (), [("gs://a", ["bucket-check", "list gs://a"])]),
        ("index", "big", ("pre", "list_source"), ["index"]),
        ("side", "small", (), ["non-live"]),
        ("index_rows", "small", ("index",), ["index-rows"]),
        ("publish_r2", "medium", ("index_rows", "side"), ["publish-r2"]),
        ("interval_store", "big", ("publish_r2",), ["interval-store"]),
        ("post", "post", ("index_rows", "interval_store", "side"), ["index-sync", "index-gc", "warm-cache", "probe"]),
    ]
    assert build(prof(**base, machines={"side": {"type": "e2-standard-4"}}))["side"].label == "side"


@pytest.mark.parametrize("poller, nodes", [
    (False, ["pre", "list_source", "index", "index_rows", "post"]),
    (True, ["list_source", "index", "index_rows", "post"]),
])
def test_access_ingest_poller_leaves_the_scan(poller: bool, nodes: list[str]):
    """`options.access-ingest.poller` (specs/access-log-freshness.md): the deployment's poller runs the ingest, so the
    scan has no `pre` task and `index` waits on the lists only."""
    p = prof(data="gs://d", layout={"layer2": "l2/{scan}/", "snapshots": "", "listing": "l2/{scan}/"}, steps=["access-ingest"],
             skip=["static-names", "publish-r2", "interval-store", "over-time", "index-gc", "warm-cache", "probe", "digest"],
             options={"access-ingest": {"args": ["-P", "4"], "poller": poller},
                      "index": {"mode": "path-index", "access": "access/agg/*/*.parquet"}})
    d = build(p)
    assert (list(d.names), d["index"].deps) == (nodes, (*nodes[:-3],))


@pytest.mark.parametrize("data, skip, static_deps", [
    ("/d", [], ("publish_r2",)),
    ("gs://dvx", [], ("index",)),
    ("/d", ["publish-r2"], ("index",)),
])
def test_a_local_data_dir_orders_static_names_after_publish(data: str, skip: list[str], static_deps: tuple[str, ...]):
    """On a local data dir `static-names` reads earlier scans from the serving store, so it runs after this scan's
    publish; on a GCS one it overlaps publish."""
    p = prof(data=data, sources=["r2://b"], skip=["digest", *skip], options={"static-names": {"gen": "g"}})
    assert build(p)["static_names"].deps == static_deps


def test_static_names_can_have_its_own_machine():
    from dataclasses import replace

    default = load(FIX / "cw-s3.yml")
    sized = replace(default, machines={**default.machines, "static": Machine(type="e2-standard-4", cpus=4, memory="14 GB")})
    assert [build(p)["static_names"].label for p in (default, sized)] == ["small", "static"]
    assert resources(sized, build(sized)["static_names"]) == Machine(type="e2-standard-4", cpus=4, memory="14 GB", time="6h")


def test_sharded_index_fans_out_parts():
    """`options.index.parts`: one `index_part` task per part, after every list; the merging `index` after them all."""
    p = prof(sources=["s3://a", "s3://c"], layout={"layer2": "l2/{scan}/", "snapshots": "", "listing": "listing/{scan}/"},
             skip=["digest", "static-names", "over-time"], machines={"index_part": {"type": "n2-highmem-8"}},
             options={"index": {"mode": "path-index", "parts": {"c": ["m"]}}})
    d = build(p)
    assert shape(d)[1:3] == [
        ("index_part", "index_part", ("list_source",), [("a", ["index a"]), ("c~0", ["index c~0"]), ("c~1", ["index c~1"])]),
        ("index", "big", ("index_part",), ["index"]),
    ]
    assert d["index_part"].fanout == "parts"


def test_resources():
    """A list task's machine is its source's (`machine`, `disk`, `fallback`), else `machines.list`'s; any other task's
    its label's; nothing named: the executor's default."""
    p = load(FIX / "cw-s3.yml")
    d = build(p)
    ls = d["list_source"]
    assert [resources(p, ls, t) for t in ls.tasks] == [
        Machine("n2-standard-8", Disk(100)),
        Machine("e2-standard-4", Disk(100)),
        Machine("e2-standard-4", Disk(375, "local-ssd")),
    ]
    assert (resources(p, d["index"]), resources(p, d["interval_store"])) == (Machine("n2-standard-8", Disk(200)),) * 2
    fb = prof(sources=[{"uri": "s3://a", "machine": "n2-standard-16", "fallback": ["n2d-standard-16"], "queue_timeout": 10}],
              executor={"kind": "google-batch", "project": "p", "region": "r", "image": "img"}, work="gs://w/nf", data="gs://w",
              skip=["static-names", "digest"])
    fd = build(fb)
    assert resources(fb, fd["list_source"], fd["list_source"].tasks[0]) == Machine(
        "n2-standard-16", fallback=("n2d-standard-16",), queue_timeout=10)
    assert resources(fb, fd["index"]) == Machine()
    with pytest.raises(ValueError) as e:
        resources(p, ls)
    assert str(e.value) == "list_source: a source's task's resources are its own (pass the task)"


def test_a_dag_is_topological_and_named_once():
    t = (Task((Call("index"),)),)
    with pytest.raises(ValueError) as e:
        ScanDag((Node("index", ("list_source",), t, "big"),))
    assert str(e.value) == "scan DAG: index needs list_source, which no earlier node is"
    with pytest.raises(ValueError) as e:
        ScanDag((Node("index", (), t, "big"), Node("index", (), t, "big")))
    assert str(e.value) == "scan DAG: node 'index' twice"
    with pytest.raises(ValueError) as e:
        ScanDag((Node("index", (), t, "big", fanout="buckets"),))
    assert str(e.value) == "scan DAG: index: fan-out 'buckets' (one of sources, parts)"


